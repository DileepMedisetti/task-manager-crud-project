# Import SQLAlchemy Session
# Session is used to communicate with the database.
from sqlalchemy.orm import Session

# Import Task model (Database Table)
from app.models import Task

# Import Pydantic Schemas
from app.schemas import TaskCreate, TaskUpdate, TaskPatch


# ==========================================
# CREATE TASK
# ==========================================
# Inserts a new task into the database.
#
# SQL Equivalent:
#
# INSERT INTO tasks(...)
#
def create_task(db: Session, task: TaskCreate):

    # Create a Task object
    db_task = Task(

        title=task.title,

        description=task.description
    )

    # Add the object to the session
    db.add(db_task)

    # Save the data permanently
    db.commit()

    # Refresh the object to get values
    # generated by the database
    # (Example: id)
    db.refresh(db_task)

    return db_task


# ==========================================
# GET ALL TASKS
# ==========================================
# Returns every task from the database.
#
# SQL:
#
# SELECT * FROM tasks;
#
def get_tasks(db: Session):

    return db.query(Task).all()


# ==========================================
# GET SINGLE TASK
# ==========================================
# Returns one task by id.
#
# SQL:
#
# SELECT * FROM tasks
# WHERE id = ?
#
def get_task(db: Session, task_id: int):

    return db.query(Task).filter(Task.id == task_id).first()


# ==========================================
