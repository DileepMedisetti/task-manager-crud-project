# ==========================================
# UPDATE TASK (PUT)
# ==========================================
# Replaces the entire task.
#
# SQL:
#
# UPDATE tasks
#
# All fields must be provided.
def update_task(
    db: Session,
    task_id: int,
    task: TaskUpdate
):

    db_task = get_task(db, task_id)

    if db_task:

        db_task.title = task.title

        db_task.description = task.description

        db_task.status = task.status

        db.commit()

        db.refresh(db_task)

    return db_task

# ==========================================
# PATCH TASK
# ==========================================
# Partially updates an existing task.
#
# SQL:
#
# UPDATE tasks
# SET only_the_provided_columns
# WHERE id = ?
#
# Unlike PUT, PATCH updates only the fields
# sent by the client.
#
# Example:
#
# {
#     "status": "Completed"
# }
#
def patch_task(
    db: Session,
    task_id: int,
    task: TaskPatch
):

    # Get the existing task from the database
    db_task = get_task(db, task_id)

    # Return None if the task doesn't exist
    if not db_task:
        return None

    # Convert only the fields sent by the client
    # into a dictionary.
    #
    # Example:
    #
    # Request:
    # {
    #     "status":"Completed"
    # }
    #
    # update_data becomes:
    #
    # {
    #     "status":"Completed"
    # }
    #
    update_data = task.model_dump(exclude_unset=True)

    # Update only the provided fields
    for key, value in update_data.items():
        setattr(db_task, key, value)

    # Save changes to the database
    db.commit()

    # Refresh the object
    db.refresh(db_task)

    return db_task

# ==========================================
# DELETE TASK
# ==========================================
#
# SQL:
#
# DELETE FROM tasks
#
def delete_task(
    db: Session,
    task_id: int
):

    db_task = get_task(db, task_id)

    if db_task:

        db.delete(db_task)

        db.commit()

    return db_task